/**
 * src/views/pc|mobile 의 index/숫자 jsx 를 Next 동적 import 레지스트리로 생성
 * 사용: node scripts/generate-page-registry.js
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const pagesRoot = path.join(root, 'src/views')
const outFile = path.join(pagesRoot, 'registry.js')

function listMenus (device) {
  const dir = path.join(pagesRoot, device)
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort()
}

function listScreens (device, menuId) {
  const dir = path.join(pagesRoot, device, menuId)
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir)
    .filter((name) => /^\d+\.jsx$/.test(name))
    .map((name) => name.replace(/\.jsx$/, ''))
    .sort((a, b) => Number(a) - Number(b))
}

function buildDevice (device) {
  const menus = listMenus(device)
  const indexLines = []
  const screenLines = []
  const menuIds = []

  menus.forEach((menuId) => {
    const indexPath = path.join(pagesRoot, device, menuId, 'index.jsx')
    if (fs.existsSync(indexPath)) {
      menuIds.push(menuId)
      indexLines.push(
        `  '${menuId}': () => import('@/views/${device}/${menuId}/index.jsx')`
      )
    }
    listScreens(device, menuId).forEach((no) => {
      screenLines.push(
        `  '${menuId}/${no}': () => import('@/views/${device}/${menuId}/${no}.jsx')`
      )
    })
  })

  return { menuIds, indexLines, screenLines }
}

const pc = buildDevice('pc')
const mobile = buildDevice('mobile')

const componentPages = {
  button: 'ButtonPage',
  typography: 'TypographyPage',
  link: 'LinkPage',
  icon: 'IconPage',
  container: 'ContainerPage',
  space: 'SpacePage',
  divider: 'DividerPage',
  flex: 'FlexPage',
  grid: 'GridPage',
  badge: 'BadgePage',
  tag: 'TagPage',
  card: 'CardPage',
  input: 'InputPage',
  select: 'SelectPage',
  alert: 'AlertPage',
  progress: 'ProgressPage',
  empty: 'EmptyPage',
  breadcrumb: 'BreadcrumbPage',
  tabs: 'TabsPage'
}

const testPages = {
  'sorting-menu': 'SortingMenuTestPage',
  'sorting-menu-basic': 'SortingMenuBasicTestPage',
  'filter-scroll': 'FilterScrollTestPage',
  chart: 'ChartTestPage'
}

const componentLines = Object.entries(componentPages).map(
  ([id, name]) => `  '${id}': () => import('@/views/components/${name}.jsx')`
)
const testLines = Object.entries(testPages).map(
  ([id, name]) => `  '${id}': () => import('@/views/test/${name}.jsx')`
)

const content = `/* eslint-disable */
/** Auto-generated by scripts/generate-page-registry.js — do not edit */
export const pcMenuIds = ${JSON.stringify(pc.menuIds, null, 2)}
export const mobileMenuIds = ${JSON.stringify(mobile.menuIds, null, 2)}

export const pcIndexLoaders = {
${pc.indexLines.join(',\n')}
}

export const pcScreenLoaders = {
${pc.screenLines.join(',\n')}
}

export const mobileIndexLoaders = {
${mobile.indexLines.join(',\n')}
}

export const mobileScreenLoaders = {
${mobile.screenLines.join(',\n')}
}

export const componentLoaders = {
${componentLines.join(',\n')}
}

export const testLoaders = {
${testLines.join(',\n')}
}
`

fs.writeFileSync(outFile, content)
console.log('wrote', path.relative(root, outFile))
console.log('pc menus', pc.menuIds.length, 'screens', pc.screenLines.length)
console.log('mobile menus', mobile.menuIds.length, 'screens', mobile.screenLines.length)
